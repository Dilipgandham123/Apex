const assert = require("node:assert/strict");
const { createHmac, randomBytes } = require("node:crypto");
const { PrismaClient } = require("@hyd/database");
const { hashPassword } = require("../dist/auth/password.js");

async function main() {
  const db = new PrismaClient();
  const base = process.env.API_INTEGRATION_URL ?? "http://localhost:4400/api/v1";
  const suffix = randomBytes(5).toString("hex");
  const password = `Stage5-${suffix}-Password!`;
  const call = (path, token, method = "GET", body) => fetch(`${base}${path}`, { method, headers: { authorization: `Bearer ${token}`, ...(body ? { "content-type": "application/json" } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  try {
    const school = await db.drivingSchool.create({ data: { slug: `stage5-${suffix}`, name: "Stage 5 School" } });
    const [staffRole, adminRole, customerRole] = await Promise.all(["STAFF", "SCHOOL_ADMIN", "CUSTOMER"].map(key => db.role.findUniqueOrThrow({ where: { key } })));
    const admin = await db.user.create({ data: { email: `stage5-admin-${suffix}@example.test`, displayName: "Stage 5 Admin", passwordHash: await hashPassword(password) } });
    await db.schoolMembership.create({ data: { userId: admin.id, schoolId: school.id, roleId: adminRole.id } });
    const driver = await db.user.create({ data: { email: `stage5-driver-${suffix}@example.test`, displayName: "Stage 5 Driver", passwordHash: await hashPassword(password) } });
    await db.schoolMembership.create({ data: { userId: driver.id, schoolId: school.id, roleId: staffRole.id } });
    const staff = await db.staffProfile.create({ data: { userId: driver.id, schoolId: school.id, staffCode: `DRV-${suffix}`, licenceNumber: `DL-${suffix}`, licenceExpiresAt: new Date(Date.now() + 365 * 86400000), canDriveManual: true } });
    const vehicle = await db.vehicle.create({ data: { schoolId: school.id, registrationNumber: `TS09L${suffix.slice(0, 5)}`.toUpperCase(), make: "Maruti Suzuki", model: "Swift", transmission: "MANUAL", odometerKm: 1000 } });
    await db.driverVehicleAssignment.create({ data: { staffId: staff.id, vehicleId: vehicle.id } });
    const course = await db.course.create({ data: { schoolId: school.id, code: `L-${suffix}`, name: "Manual Training", transmission: "MANUAL", price: 12000, classCount: 28, targetKmPerClass: 6, durationDays: 60 } });
    const customerUser = await db.user.create({ data: { phone: `9${suffix.replace(/\D/g, "").padEnd(9, "7").slice(0, 9)}`, displayName: "Lesson Customer" } });
    await db.schoolMembership.create({ data: { userId: customerUser.id, schoolId: school.id, roleId: customerRole.id } });
    const customer = await db.customerProfile.create({ data: { userId: customerUser.id, schoolId: school.id, customerCode: `SSA-${suffix.toUpperCase().slice(0, 6)}` } });
    const enrollment = await db.courseEnrollment.create({ data: { customerId: customer.id, courseId: course.id, courseNameSnapshot: course.name, priceSnapshot: course.price, classCountSnapshot: 28, targetKmPerClassSnapshot: 6, durationDaysSnapshot: 60, totalPayable: 12000 } });

    const login = async email => { const response = await fetch(`${base}/auth/password/login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ identifier: email, password }) }); assert.equal(response.status, 200); return (await response.json()).accessToken; };
    const staffToken = await login(driver.email);
    const adminToken = await login(admin.email);

    let response = await call(`/lessons/customers/search?query=${encodeURIComponent(customer.customerCode)}`, staffToken);
    assert.equal(response.status, 200);
    assert.equal((await response.json())[0].classesCompleted, 0);
    response = await call("/lessons/history", adminToken);
    assert.equal(response.status, 403);

    response = await call("/lessons/start", staffToken, "POST", { enrollmentId: enrollment.id, startOdometerKm: 1000, startEvidenceUrl: "https://example.test/start.jpg" });
    assert.equal(response.status, 201);
    let lesson = await response.json();
    assert.equal(lesson.classNumber, 1);
    assert.equal(lesson.status, "ACTIVE");
    response = await call("/lessons/start", staffToken, "POST", { enrollmentId: enrollment.id, startOdometerKm: 1000 });
    assert.equal(response.status, 409);
    response = await call(`/vehicles/${vehicle.id}/status`, adminToken, "PATCH", { status: "MAINTENANCE" });
    assert.equal(response.status, 400);
    response = await call(`/lessons/${lesson.id}/end`, staffToken, "POST", { endOdometerKm: 999, skills: [] });
    assert.equal(response.status, 400);
    response = await call(`/lessons/${lesson.id}/end`, staffToken, "POST", { endOdometerKm: 1006, endEvidenceUrl: "https://example.test/end.jpg", customerSummary: "Practised steering and braking.", privateNote: "Good first class.", skills: ["Steering", "Braking"] });
    assert.equal(response.status, 201);
    lesson = await response.json();
    assert.equal(lesson.status, "COMPLETED");
    assert.equal(Number(lesson.coveredKm), 6);
    assert.equal(Number(lesson.shortfallKm), 0);
    assert.equal(lesson.skills.length, 2);
    let savedEnrollment = await db.courseEnrollment.findUniqueOrThrow({ where: { id: enrollment.id } });
    assert.ok(savedEnrollment.firstLessonAt);
    assert.ok(savedEnrollment.deadlineAt);
    assert.equal(Math.round((savedEnrollment.deadlineAt - savedEnrollment.firstLessonAt) / 86400000), 60);

    response = await call("/lessons/start", staffToken, "POST", { enrollmentId: enrollment.id, startOdometerKm: 1006 });
    assert.equal(response.status, 201);
    lesson = await response.json();
    assert.equal(lesson.classNumber, 2);
    response = await call(`/lessons/${lesson.id}/end`, staffToken, "POST", { endOdometerKm: 1011, skills: ["Gear changes"] });
    assert.equal(response.status, 201);
    lesson = await response.json();
    assert.equal(lesson.status, "COMPLETED_WITH_SHORTFALL");
    assert.equal(Number(lesson.coveredKm), 5);
    assert.equal(Number(lesson.shortfallKm), 1);
    response = await call("/lessons/history", staffToken);
    assert.equal(response.status, 200);
    assert.equal((await response.json()).length, 2);
    assert.equal(Number((await db.vehicle.findUniqueOrThrow({ where: { id: vehicle.id } })).odometerKm), 1011);

    response = await call("/lessons/start", staffToken, "POST", { enrollmentId: enrollment.id, startOdometerKm: 1011 });
    assert.equal(response.status, 201);
    lesson = await response.json();
    assert.equal(lesson.classNumber, 3);
    assert.equal(Number(lesson.pendingKmBefore), 1);
    assert.equal(Number(lesson.totalTargetKm), 7);
    response = await call(`/lessons/${lesson.id}/end`, staffToken, "POST", { endOdometerKm: 1018, skills: [] });
    assert.equal(response.status, 201);
    lesson = await response.json();
    assert.equal(lesson.status, "COMPLETED");
    assert.equal(Number(lesson.shortfallKm), 0);
    let ledger = await db.kilometreLedgerEntry.findMany({ where: { enrollmentId: enrollment.id }, orderBy: { createdAt: "asc" } });
    assert.deepEqual(ledger.map(entry => [entry.type, Number(entry.amountKm)]), [["SHORTFALL", 1], ["RECOVERY", 1]]);
    assert.equal(ledger[0].shortfallLessonId, ledger[1].shortfallLessonId);
    assert.equal(ledger[1].recoveryLessonId, lesson.id);

    await db.courseEnrollment.update({ where: { id: enrollment.id }, data: { deadlineAt: new Date(Date.now() - 86400000) } });
    response = await call("/lessons/start", staffToken, "POST", { enrollmentId: enrollment.id, startOdometerKm: 1018 });
    assert.equal(response.status, 400);
    response = await call("/training/enrollments", adminToken);
    assert.equal(response.status, 200);
    let training = (await response.json()).find(item => item.id === enrollment.id);
    assert.equal(training.status, "EXPIRED");
    assert.equal(Number(training.pendingKm), 0);
    const extendedDeadline = new Date(Date.now() + 10 * 86400000).toISOString();
    response = await call(`/training/enrollments/${enrollment.id}/deadline-extensions`, adminToken, "POST", { newDeadline: extendedDeadline, reason: "Approved medical leave" });
    assert.equal(response.status, 201);
    response = await call(`/training/enrollments/${enrollment.id}/kilometre-adjustments`, adminToken, "POST", { adjustmentKm: 1, reason: "Verified notebook correction" });
    assert.equal(response.status, 201);
    training = (await (await call("/training/enrollments", adminToken)).json()).find(item => item.id === enrollment.id);
    assert.equal(training.status, "ACTIVE");
    assert.equal(Number(training.pendingKm), 1);
    assert.equal(training.deadlineExtensions.length, 1);
    response = await call(`/training/enrollments/${enrollment.id}/kilometre-adjustments`, staffToken, "POST", { adjustmentKm: -1, reason: "Staff must not correct" });
    assert.equal(response.status, 403);
    response = await call(`/training/enrollments/${enrollment.id}/kilometre-adjustments`, adminToken, "POST", { adjustmentKm: -2, reason: "Would become negative" });
    assert.equal(response.status, 400);
    assert.ok((await db.auditLog.count({ where: { entityId: enrollment.id, action: { in: ["enrollment.deadline_extended", "kilometres.adjusted"] } } })) >= 2);
    response = await fetch(`${base}/auth/customer/request-otp`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ phone: customerUser.phone }) });
    assert.equal(response.status, 200);
    const challenge = await response.json();
    response = await fetch(`${base}/auth/customer/verify-otp`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ challengeId: challenge.challengeId, code: challenge.developmentCode }) });
    assert.equal(response.status, 200);
    const customerToken = (await response.json()).accessToken;
    response = await call("/customer/me/overview", customerToken);
    assert.equal(response.status, 200);
    const overview = await response.json();
    assert.equal(overview.customer.customerCode, customer.customerCode);
    assert.equal(overview.enrollment.id, enrollment.id);
    assert.equal(overview.enrollment.classesCompleted, 3);
    assert.equal(Number(overview.enrollment.pendingKm), 1);
    assert.equal(Number(overview.enrollment.pendingAmount), 12000);
    assert.equal(overview.lessons[2].privateNote, undefined);
    assert.equal(overview.lessons[2].startEvidenceUrl, undefined);
    response = await call("/customer/me/overview", adminToken);
    assert.equal(response.status, 403);
    response = await call("/payments/manual", staffToken, "POST", { enrollmentId: enrollment.id, amount: 3000, method: "CASH" });
    assert.equal(response.status, 403);
    response = await call("/payments/manual", adminToken, "POST", { enrollmentId: enrollment.id, amount: 3000, method: "UPI", reference: "UPI-TEST-001", note: "First instalment" });
    assert.equal(response.status, 201);
    const manualPayment = await response.json();
    assert.match(manualPayment.receiptNumber, /^SSA-/);
    response = await call("/payments/customer/me", customerToken);
    assert.equal(response.status, 200);
    let paymentSummary = await response.json();
    assert.equal(Number(paymentSummary.paidAmount), 3000);
    assert.equal(Number(paymentSummary.pendingAmount), 9000);
    response = await call(`/payments/${manualPayment.id}/refunds`, adminToken, "POST", { amount: 1000, reason: "Customer requested partial refund" });
    assert.equal(response.status, 201);
    paymentSummary = await (await call("/payments/customer/me", customerToken)).json();
    assert.equal(Number(paymentSummary.paidAmount), 2000);
    assert.equal(Number(paymentSummary.pendingAmount), 10000);

    const orderId = `order_${suffix}`, paymentId = `pay_${suffix}`;
    await db.payment.create({ data: { schoolId: school.id, enrollmentId: enrollment.id, amount: 2000, method: "RAZORPAY", status: "PENDING", receiptNumber: `RZP-${suffix}`, providerOrderId: orderId } });
    response = await call("/payments/razorpay/verify", customerToken, "POST", { razorpayOrderId: orderId, razorpayPaymentId: paymentId, razorpaySignature: "0".repeat(64) });
    assert.equal(response.status, 401);
    const checkoutSignature = createHmac("sha256", process.env.RAZORPAY_KEY_SECRET).update(`${orderId}|${paymentId}`).digest("hex");
    response = await call("/payments/razorpay/verify", customerToken, "POST", { razorpayOrderId: orderId, razorpayPaymentId: paymentId, razorpaySignature: checkoutSignature });
    assert.equal(response.status, 201);
    response = await call("/payments/razorpay/verify", customerToken, "POST", { razorpayOrderId: orderId, razorpayPaymentId: paymentId, razorpaySignature: checkoutSignature });
    assert.equal(response.status, 201);

    const webhookOrderId = `order_hook_${suffix}`, webhookPaymentId = `pay_hook_${suffix}`;
    await db.payment.create({ data: { schoolId: school.id, enrollmentId: enrollment.id, amount: 1000, method: "RAZORPAY", status: "PENDING", receiptNumber: `HOOK-${suffix}`, providerOrderId: webhookOrderId } });
    const webhookBody = JSON.stringify({ event: "payment.captured", payload: { payment: { entity: { id: webhookPaymentId, order_id: webhookOrderId, status: "captured" } } } });
    const webhookSignature = createHmac("sha256", process.env.RAZORPAY_WEBHOOK_SECRET).update(webhookBody).digest("hex");
    const webhook = () => fetch(`${base}/payments/razorpay/webhook`, { method: "POST", headers: { "content-type": "application/json", "x-razorpay-signature": webhookSignature, "x-razorpay-event-id": `evt_${suffix}` }, body: webhookBody });
    response = await webhook(); assert.equal(response.status, 201);
    response = await webhook(); assert.equal(response.status, 201); assert.equal((await response.json()).duplicate, true);
    assert.equal(await db.paymentWebhookEvent.count({ where: { providerEventId: `evt_${suffix}` } }), 1);
    paymentSummary = await (await call("/payments/customer/me", customerToken)).json();
    assert.equal(Number(paymentSummary.paidAmount), 5000);
    assert.equal(Number(paymentSummary.pendingAmount), 7000);
    response = await call("/payments/manual", adminToken, "POST", { enrollmentId: enrollment.id, amount: 8000, method: "CASH" });
    assert.equal(response.status, 400);
    response = await call("/complaints", customerToken, "POST", { subject: "Class distance concern", description: "Please review the distance recorded for this class.", lessonId: lesson.id, staffId: staff.id, vehicleId: vehicle.id, paymentId: manualPayment.id, attachments: [{ url: "https://res.cloudinary.com/demo/image/upload/evidence.jpg", publicId: `complaint-${suffix}`, fileName: "evidence.jpg", mimeType: "image/jpeg", sizeBytes: 1200 }] });
    assert.equal(response.status, 201);
    const complaint = await response.json();
    assert.equal(complaint.lesson.classNumber, 3);
    response = await call("/complaints", staffToken); assert.equal(response.status, 403);
    response = await call(`/complaints/${complaint.id}/replies`, adminToken, "POST", { body: "Reviewing the lesson record now.", private: false }); assert.equal(response.status, 201);
    response = await call(`/complaints/${complaint.id}/replies`, adminToken, "POST", { body: "Odometer evidence matches the notebook.", private: true }); assert.equal(response.status, 201);
    response = await call("/complaints/customer/me", customerToken); assert.equal(response.status, 200);
    let customerComplaints = await response.json();
    assert.equal(customerComplaints[0].messages.length, 1);
    assert.equal(customerComplaints[0].messages[0].body, "Reviewing the lesson record now.");
    response = await call(`/complaints/${complaint.id}`, adminToken, "PATCH", { status: "RESOLVED" }); assert.equal(response.status, 400);
    response = await call(`/complaints/${complaint.id}`, adminToken, "PATCH", { status: "RESOLVED", priority: "HIGH", resolutionOutcome: "The recorded distance was verified against the lesson evidence." }); assert.equal(response.status, 200);
    customerComplaints = await (await call("/complaints/customer/me", customerToken)).json();
    assert.equal(customerComplaints[0].status, "RESOLVED");
    assert.equal(customerComplaints[0].resolutionOutcome, "The recorded distance was verified against the lesson evidence.");
    assert.equal(customerComplaints[0].messages.some(item => item.visibility === "PRIVATE"), false);
    response = await call(`/complaints/${complaint.id}/customer-replies`, customerToken, "POST", { body: "Thank you." }); assert.equal(response.status, 400);
    assert.ok(await db.auditLog.count({ where: { entityId: complaint.id, action: { in: ["complaint.submitted", "complaint.updated"] } } }));
    response = await call("/reports/dashboard", adminToken); assert.equal(response.status, 200);
    const dashboard = await response.json();
    assert.equal(dashboard.operations.classesToday >= 3, true);
    assert.equal(Number(dashboard.totals.pendingKilometres), 1);
    assert.equal(Number(dashboard.totals.pendingPayments), 7000);
    response = await call("/reports", adminToken); assert.equal(response.status, 200);
    const reports = await response.json();
    assert.equal(reports.summary.customers >= 1, true);
    assert.equal(reports.summary.lessons >= 3, true);
    assert.equal(Number(reports.summary.kilometres) >= 18, true);
    assert.equal(Number(reports.summary.revenue), 5000);
    assert.equal(Number(reports.summary.pendingPayments), 7000);
    assert.equal(reports.customerRows.find(item => item.id === enrollment.id).classesCompleted, 3);
    assert.equal(reports.complaintRows.find(item => item.id === complaint.id).status, "RESOLVED");
    response = await call("/reports/staff/me", staffToken); assert.equal(response.status, 200);
    const staffDashboard = await response.json();
    assert.equal(staffDashboard.staff.staffCode, staff.staffCode);
    assert.equal(staffDashboard.today.classes >= 3, true);
    response = await call("/reports/dashboard", staffToken); assert.equal(response.status, 403);
    response = await call("/reports", customerToken); assert.equal(response.status, 403);
    console.log("integration: training, payments, complaints and source-reconciled role dashboards/reports passed");
  } finally { await db.$disconnect(); }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
